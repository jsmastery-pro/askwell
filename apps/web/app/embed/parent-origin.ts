// The loader passes the host page's origin; postMessage needs an exact origin, never "*".
export function parentOriginFrom(value: unknown): string | null {
  if (typeof value !== "string") return null;
  try {
    const url = new URL(value);
    return url.protocol === "https:" || url.protocol === "http:" ? url.origin : null;
  } catch {
    return null;
  }
}
